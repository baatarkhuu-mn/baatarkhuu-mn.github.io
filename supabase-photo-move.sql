-- 1) Админ хаалттай сангийн зургийг устгаж чадна (зөөсний дараа эхийг нь цэвэрлэнэ)
drop policy if exists "admin delete feedback photo" on storage.objects;
create policy "admin delete feedback photo"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'feedback-photos');

-- 2) Админ нийтийн сангийн файлыг дарж бичиж чадна (upsert хийхэд хэрэгтэй)
drop policy if exists "admin update public photo" on storage.objects;
create policy "admin update public photo"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'feedback-public')
  with check (bucket_id = 'feedback-public');

